def _d(v) -> Decimal:
    if v in (None, ""):
        return Decimal("0")
    return Decimal(str(v))


def _month_to_date_window() -> tuple[datetime, datetime]:
    """1st of the current calendar month through now — the default window
    product decided every Records/Compliance report should use, replacing
    the old rolling-N-days shorthand."""
    now = datetime.now(timezone.utc)
    start = now.replace(day=1, hour=0, minute=0, second=0, microsecond=0)
    return start, now


def _resolve_date_window(date_from: Optional[str], date_to: Optional[str]) -> tuple[datetime, datetime]:
    """Explicit From/To (YYYY-MM-DD) query params for reports that used to
    take a rolling-N-days `date_range` shorthand. Either side omitted falls
    back to the current-month default on that side; both omitted falls back
    to the full current-month-to-date window."""
    if not date_from and not date_to:
        return _month_to_date_window()

    default_start, default_end = _month_to_date_window()
    try:
        start = (
            datetime.fromisoformat(date_from).replace(hour=0, minute=0, second=0, microsecond=0, tzinfo=timezone.utc)
            if date_from
            else default_start
        )
        end = (
            datetime.fromisoformat(date_to).replace(hour=23, minute=59, second=59, microsecond=0, tzinfo=timezone.utc)
            if date_to
            else default_end
        )
    except ValueError as e:
        raise HTTPException(status_code=422, detail="date_from/date_to must be YYYY-MM-DD") from e
    if start > end:
        raise HTTPException(status_code=422, detail="date_from must be on or before date_to")
    return start, end


def _capture_export_failure(report_type: str, error: Exception) -> None:
    """Explicit domain-tagged Sentry event for a compliance-export failure.
    Best-effort — never raises, no-op if SENTRY_DSN isn't configured. Same
    shape as services/data_transfer/observability.py's capture_failure."""
    try:
        import sentry_sdk  # type: ignore

        with sentry_sdk.push_scope() as scope:
            scope.set_tag("domain", "admin")
            scope.set_tag("surface", "backend")
            scope.set_tag("report_type", report_type)
            sentry_sdk.capture_exception(error)
    except Exception as sentry_err:
        logger.debug(f"compliance Sentry capture skipped: {sentry_err}")


async def _log_compliance_export(admin: dict, report_type: str, params: dict, row_count: int) -> None:
    """Best-effort write to the compliance_export_events audit table. A
    failure here must not block the admin from getting their report, but
    must surface loudly (CLAUDE.md: never silently swallow DB errors) —
    logged as an error, not a warning, so it's actionable."""
    try:
        await db_supabase.insert_one(
            "compliance_export_events",
            {
                "admin_user_id": admin.get("id") or admin.get("user_id"),
                "report_type": report_type,
                "params": params,
                "row_count": row_count,
            },
        )
    except Exception as e:
        logger.error(f"Failed to log compliance_export_events for {report_type}: {e}", exc_info=True)


# Known production tax_breakdown labels (services/fare_service.py /
# features.py's _apply_tax writes exactly these — "GST", "PST", "HST"; see
# features.py:939-945). Matched by exact label, not substring, so a future
# label like "GST/HST" or an unrelated fee containing "gst" can't silently
# shift money between buckets — it lands in `unrecognized` instead, which
# is surfaced as its own column rather than folded into GST/PST/HST.
_KNOWN_TAX_LABELS = ("GST", "PST", "QST", "HST")

# Applies to every source query in this module. A regulatory/tax export
# that silently drops rows past this cap would misstate the filing with no
# visible signal — _check_truncated() below turns that into a loud error
# log plus a visible "(TRUNCATED)" marker on the exported report instead.
_ROW_LIMIT = 10000


# AI-3's stated acceptance criterion (docs/threat-model/admin-panel.md;
# ACTION_ITEMS.md B10): "any export > 1,000 rows requires a second admin's
# approval." Dark-launched behind settings.dual_approval_exports_enabled
# (migration 268, default false) -- until an admin explicitly flips it on,
# _check_export_gate always returns None (ungated) and every report here
# behaves exactly as it did before this gate existed.
_APPROVAL_GATE_ROW_THRESHOLD = 1000

# CRA T4A (Box 048, "Fees for Services") reporting threshold — matches
# utils/t4a_annual_job.py's own _T4A_THRESHOLD constant (kept separate
# rather than imported: that module owns the annual push-notification
# job, a different concern from this admin-triggered export).
_T4A_THRESHOLD = Decimal("500.00")


async def _check_export_gate(admin: dict, route_key: str, gate_params: dict, row_count: int) -> Optional[JSONResponse]:
    """Returns a 202 JSONResponse if this export needs (and doesn't yet
    have) a second admin's approval; returns None if the caller should
    proceed with generating the report as normal -- either the gate is
    off, the export is under threshold, or an approved grant exists (in
    which case it's consumed here, single-use)."""
    settings = await get_app_settings()
    if not settings.get("dual_approval_exports_enabled"):
        return None
    if row_count <= _APPROVAL_GATE_ROW_THRESHOLD:
        return None

    grant = await admin_export_approvals.find_approved_grant(
        requested_by=admin["id"], route_key=route_key, params=gate_params
    )
    if grant:
        await admin_export_approvals.consume(grant["id"])
        return None

    pending = await admin_export_approvals.find_pending_request(
        requested_by=admin["id"], route_key=route_key, params=gate_params
    )
    if not pending:
        pending = await admin_export_approvals.create_request(
            requested_by=admin["id"], route_key=route_key, params=gate_params, row_count=row_count
        )
    return JSONResponse(
        status_code=202,
        content={
            "approval_required": True,
            "request_id": pending["id"],
            "status": pending["status"],
            "row_count": row_count,
        },
    )


def _check_truncated(fetched_count: int, report_type: str) -> bool:
    if fetched_count < _ROW_LIMIT:
        return False
    logger.error(
        f"{report_type} export hit the {_ROW_LIMIT}-row fetch limit — report is truncated "
        f"and may misstate the true totals for the requested range. Narrow the date range "
        f"or add a driver_id filter to get a complete export."
    )
    return True


async def _gst_pst_rows(start_date: datetime, end_date: datetime) -> tuple[list[dict], Decimal, Decimal, Decimal, bool]:
    """Sum GST/PST/HST from completed rides' persisted tax_breakdown, grouped
    by calendar month. Reads what was actually charged (ride.tax_breakdown),
    the same field the rider receipt (utils/receipt_pdf.py) and email
    receipt (utils/email_receipt.py) render from — never recomputed."""
    rides = await db_supabase.get_rows(
        "rides",
        {
            "status": "completed",
            "ride_completed_at": {"$gte": start_date.isoformat(), "$lte": end_date.isoformat()},
        },
        columns="id,ride_completed_at,tax_breakdown,total_fare",
        limit=_ROW_LIMIT,
    )
    truncated = _check_truncated(len(rides), "gst_pst_remittance")

    by_month: dict[str, dict[str, Decimal]] = {}
    gst_total = Decimal("0")
    pst_total = Decimal("0")
    hst_total = Decimal("0")
    for ride in rides:
        completed_at = ride.get("ride_completed_at") or ""
        month_key = completed_at[:7] if len(completed_at) >= 7 else "unknown"
        tax_breakdown = ride.get("tax_breakdown") or {}
        if not isinstance(tax_breakdown, dict):
            continue
        bucket = by_month.setdefault(
            month_key,
            {"GST": Decimal("0"), "PST": Decimal("0"), "HST": Decimal("0"), "unrecognized": Decimal("0")},
        )
        for label, payload in tax_breakdown.items():
            if not isinstance(payload, dict):
                continue
            amount = _d(payload.get("amount"))
            if amount == 0:
                continue
            label_upper = label.upper()
            if label_upper == "GST":
                bucket["GST"] += amount
                gst_total += amount
            elif label_upper in ("PST", "QST"):
                bucket["PST"] += amount
                pst_total += amount
            elif label_upper == "HST":
                bucket["HST"] += amount
                hst_total += amount
            else:
                # Not a known tax label — never silently fold an
                # unrecognized amount into GST/PST/HST (CLAUDE.md: don't
                # silently swallow errors that could misstate a filing).
                logger.error(
                    f"Unrecognized tax_breakdown label '{label}' on ride {ride.get('id')} "
                    f"— excluded from GST/PST/HST totals, reported separately as 'unrecognized'"
                )
                bucket["unrecognized"] += amount

    rows = [
        {
            "month": month,
            "gst": f"{v['GST']:.2f}",
            "pst": f"{v['PST']:.2f}",
            "hst": f"{v['HST']:.2f}",
            "unrecognized_tax": f"{v['unrecognized']:.2f}",
            "total_tax": f"{(v['GST'] + v['PST'] + v['HST'] + v['unrecognized']):.2f}",
        }
        for month, v in sorted(by_month.items())
    ]
    return rows, gst_total, pst_total, hst_total, truncated


def _render_tabular_report(
    *,
    title: str,
    filename_base: str,
    fieldnames: list[str],
    rows: list[dict],
    subtitle: "str | list[str]",
    format: str,
    pdf_landscape: bool = False,
    pdf_col_widths: list[float] | None = None,
) -> Response:
    """Shared branded-report rendering for any (fieldnames, rows) tabular
    report — used by both the GST/PST remittance and insurance-period audit
    endpoints so format handling (pdf/csv/xlsx/docx) lives in one place.

    pdf_landscape/pdf_col_widths: reports with several columns or long
    cell values (UUIDs, ISO timestamps) need landscape orientation and
    wider ratios for those columns — passed per-report since each report's
    column shape differs. Regression: an earlier fixed-width single-line
    pdf.cell() renderer clipped/overlapped text into an unreadable table
    the moment real data (full UUIDs, microsecond timestamps) was used —
    confirmed against a real downloaded report from the live admin portal.
    Now uses fpdf2's native Table API (report_branding.render_pdf_table),
    which wraps text and syncs row heights instead of clipping."""
    if format == "csv":
        buf = io.StringIO()
        writer = csv.DictWriter(buf, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
        return Response(
            content=buf.getvalue().encode("utf-8-sig"),
            media_type="text/csv",
            headers={"Content-Disposition": f'attachment; filename="{filename_base}.csv"'},
        )

    if format == "xlsx":
        wb, ws = report_branding.new_branded_workbook(title, subtitle)
        report_branding.write_branded_table(ws, fieldnames, rows)
        buf = io.BytesIO()
        wb.save(buf)
        return Response(
            content=buf.getvalue(),
            media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            headers={"Content-Disposition": f'attachment; filename="{filename_base}.xlsx"'},
        )

    if format == "docx":
        doc = report_branding.new_branded_document(title, subtitle)
        report_branding.add_branded_table(doc, fieldnames, rows)
        buf = io.BytesIO()
        doc.save(buf)
        return Response(
            content=buf.getvalue(),
            media_type="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            headers={"Content-Disposition": f'attachment; filename="{filename_base}.docx"'},
        )

    # default: pdf
    pdf = report_branding.new_branded_pdf(title, subtitle, landscape=pdf_landscape)
    report_branding.render_pdf_table(pdf, fieldnames, rows, col_widths=pdf_col_widths)
    report_branding.render_branded_pdf_footer(pdf)
    return Response(
        content=bytes(pdf.output()),
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename_base}.pdf"'},
    )


def _require_spinr_ca(email_to: Optional[str]) -> None:
    """Reports may only be emailed to a @spinr.ca address — this is an
    internal-admin delivery convenience, not a general "email this PDF
    anywhere" feature, so the domain is hard-validated rather than trusting
    whatever the admin typed."""
    if email_to and not email_to.lower().strip().endswith("@spinr.ca"):
        raise HTTPException(status_code=422, detail="Reports can only be emailed to a @spinr.ca address")


async def _deliver_report(resp: Response, email_to: Optional[str], admin: dict, title: str) -> Response:
    """If `email_to` is set, email the already-rendered report as an
    attachment (reusing the Response _render_tabular_report already built —
    no separate rendering path to keep in sync) and return a small JSON
    confirmation instead of streaming the file to the browser. Otherwise
    return `resp` unchanged for a normal download."""
    if not email_to:
        return resp
    disposition = resp.headers.get("content-disposition", "")
    filename = disposition.split("filename=", 1)[-1].strip('"') if "filename=" in disposition else "report"
    try:
        sent = await send_transactional_email(
            to=email_to,
            subject=f"Spinr — {title}",
            text=f"Attached: {title}, generated by {admin.get('email') or admin.get('id')}.",
            attachments=[{"filename": filename, "content": resp.body}],
            email_type="admin_report",
            recipient_user_id=None,
        )
    except Exception as e:
        # send_transactional_email's own docstring says it returns True/False
        # and never raises, but an unhandled exception here (e.g. from the
        # SES/Resend client construction, or DB error in the suppression
        # check) previously fell through to FastAPI's default 500, which the
        # admin dashboard's generic error toast rendered as the unhelpful
        # "Could not generate report / Internal Server Error". Catch and log
        # the real exception loudly, then surface the same clean 502 the
        # `not sent` branch already gives for an expected send failure.
        logger.error("compliance report email send failed for %s: %s", title, e, exc_info=True)
        raise HTTPException(
            status_code=502, detail="Could not send the report email — try downloading it instead"
        ) from e
    if not sent:
        raise HTTPException(status_code=502, detail="Could not send the report email — try downloading it instead")
    return Response(content=f'{{"emailed_to": "{email_to}"}}', media_type="application/json")


@api_router.get("/gst-pst-remittance")
@limiter.limit("10/minute")
async def get_gst_pst_remittance(
    request: Request,
    date_from: Optional[str] = Query(None, description="YYYY-MM-DD; defaults to the 1st of the current month"),
    date_to: Optional[str] = Query(None, description="YYYY-MM-DD; defaults to today"),
    format: str = Query("pdf", pattern="^(pdf|csv|xlsx|docx)$"),
    email_to: Optional[str] = Query(
        None, description="Email the report to this @spinr.ca address instead of downloading it"
    ),
    admin: dict = Depends(get_admin_user),
):
    """GST/PST tax remittance summary, grouped by month, over completed
    rides in the requested date range. Spinr-branded (never a fixed
    regulator format — CRA remittance filing has no prescribed layout,
    unlike SGI's forms)."""
    _require_spinr_ca(email_to)
    start_date, end_date = _resolve_date_window(date_from, date_to)

    try:
        rows, gst_total, pst_total, hst_total, truncated = await _gst_pst_rows(start_date, end_date)
    except Exception as e:
        logger.error(f"Failed to build GST/PST remittance summary: {e}", exc_info=True)
        _capture_export_failure("gst_pst_remittance", e)
        metrics.inc("spinr_admin_compliance_export_total", {"report_type": "gst_pst_remittance", "outcome": "error"})
        raise HTTPException(status_code=503, detail="Compliance report data unavailable — database error") from e

    gate_response = await _check_export_gate(
        admin,
        "compliance.gst_pst_remittance",
        {"date_from": date_from, "date_to": date_to, "format": format, "email_to": email_to},
        len(rows),
    )
    if gate_response is not None:
        return gate_response

    fieldnames = ["month", "gst", "pst", "hst", "unrecognized_tax", "total_tax"]
    # The header states what the report is and what period it covers — the
    # GST/PST/HST figures themselves belong in the table body (a TOTAL row
    # below), not crammed under the title next to the date range. Previously
    # this put a "GST: $x  PST: $y  HST: $z" line directly under the title,
    # which read as a stray calculation rather than part of the document.
    subtitle = report_branding.period_label(start_date, end_date)
    if truncated:
        subtitle += f" — ⚠ TRUNCATED at {_ROW_LIMIT} rides; narrow the date range for a complete filing"

    month_row_count = len(rows)
    if rows:
        rows = [
            *rows,
            {
                "month": "TOTAL",
                "gst": f"{gst_total:.2f}",
                "pst": f"{pst_total:.2f}",
                "hst": f"{hst_total:.2f}",
                "unrecognized_tax": f"{sum(_d(r['unrecognized_tax']) for r in rows):.2f}",
                "total_tax": f"{(gst_total + pst_total + hst_total):.2f}",
            },
        ]

    await _log_compliance_export(
        admin,
        "gst_pst_remittance",
        {"format": format, "start": start_date.isoformat(), "end": end_date.isoformat()},
        month_row_count,
    )
    metrics.inc("spinr_admin_compliance_export_total", {"report_type": "gst_pst_remittance", "outcome": "success"})

    resp = _render_tabular_report(
        title="GST/PST Remittance Summary",
        filename_base="gst_pst_remittance",
        fieldnames=fieldnames,
        rows=rows,
        subtitle=subtitle,
        format=format,
    )
    return await _deliver_report(resp, email_to, admin, "GST/PST Remittance Summary")


# ── Driver Roster (formerly "Knight Archer Driver Onboarding") ───────
#
# Renamed from a Knight-Archer-specific name to a generic one: the report
# itself was never Knight-Archer-specific (it's every onboarded driver's
# license/status info, full roster regardless of status), only its stated
# purpose was — keeping Knight Archer Insurance (the broker) current on
# active drivers, monthly. The old name baked a single consumer into the
# report's identity; the content is generically useful (e.g. an internal
# monthly driver-roster review) and other insurers/consumers can use the
# same export without a name implying it's Knight-Archer-only.
#
# _PERIOD_LABELS stays here (moved from the now-retired Insurance-Period
# Regulatory Audit report below) — the new per-trip insurance billing
# reports still need it to label Period 2 vs Period 3 rows.

_PERIOD_LABELS = {
    0: "0 — Offline",
    1: "1 — Available (contingent liability)",
    2: "2 — En route to pickup (primary commercial)",
    3: "3 — Passenger aboard (primary commercial, full)",
}


async def _driver_roster_rows(status: Optional[str], include_deleted: bool = False) -> tuple[list[dict], bool]:
    """Pull every onboarded driver's license/status info. Deliberately
    covers every driver status, not just active — Knight Archer's original
    ask was for "driver onboarded, driver license, with all status", i.e.
    the full roster regardless of where a driver currently sits in the
    pipeline (pending/needs_review/active/suspended/banned); the optional
    `status` filter narrows to just "active" for a consumer that only
    wants that slice.

    Drivers who deleted their account are excluded by default. Account
    deletion cannot change `drivers.status` — there is no 'deleted' value in
    the status set — so a driver who left kept status='active' and went on
    appearing on the roster this report sends to an insurer/regulator as a
    currently-onboarded driver. This roster answers "who is on the road now";
    telling the regulator someone has stopped driving is the SGI D00032/D00033
    'remove' form's job, not a silent omission from a status column.

    `include_deleted=True` restores the old behavior for an operator auditing
    historical roster membership, and tags each row so the two are never
    confused on the page.
    """
    filters: dict = {}
    if status:
        filters["status"] = status
    if not include_deleted:
        filters["deleted_at"] = None  # compiles to PostgREST `is.null`

    drivers = await db_supabase.get_rows(
        "drivers",
        filters,
        columns="id,name,first_name,last_name,license_number,license_class,status,created_at,deleted_at",
        order="created_at",
        desc=True,
        limit=_ROW_LIMIT,
    )
    truncated = _check_truncated(len(drivers), "driver_roster")
    if not drivers:
        return [], truncated

    # license_number is vault-encrypted at rest — same decrypt helper
    # sgi_forms.py uses for the SGI forms, since this report needs the real
    # license number too, not the encrypted token.
    drivers = [await _decrypt_driver_pii(d) for d in drivers]

    rows = [
        {
            "driver_name": d.get("name") or f"{d.get('first_name', '')} {d.get('last_name', '')}".strip() or d["id"],
            "license_number": d.get("license_number") or "",
            "license_class": d.get("license_class") or "",
            # A soft-deleted row still carries its pre-deletion status (usually
            # 'active'), which would read as a working driver. Only reachable
            # when include_deleted=True.
            "status": "deleted" if d.get("deleted_at") else (d.get("status") or ""),
            "onboarded_at": report_branding.format_report_timestamp(d.get("created_at")),
        }
        for d in drivers
    ]
    return rows, truncated


@api_router.get("/driver-roster")
@limiter.limit("10/minute")
async def get_driver_roster(
    request: Request,
    status: Optional[str] = Query(None, description="Exact match on drivers.status; omit to include every status"),
    include_deleted: bool = Query(
        False,
        description="Include drivers who deleted their account (excluded by default; they are not on the road)",
    ),
    format: str = Query("pdf", pattern="^(pdf|csv|xlsx|docx)$"),
    email_to: Optional[str] = Query(
        None, description="Email the report to this @spinr.ca address instead of downloading it"
    ),
    admin: dict = Depends(get_admin_user),
):
    """Driver roster — name, license number, license class, and current
    status, for every onboarded driver regardless of status (or filtered
    to one status). Original use case: keeping Knight Archer Insurance (the
    broker) current on active drivers, monthly cadence — content is
    generic enough for other roster-review consumers too. Spinr-branded,
    not a fixed regulator form (see module docstring).

    Drivers who deleted their account are excluded unless `include_deleted`
    is set — see `_driver_roster_rows` for why a status filter alone does not
    catch them."""
    _require_spinr_ca(email_to)
    try:
        rows, truncated = await _driver_roster_rows(status, include_deleted=include_deleted)
    except Exception as e:
        logger.error(f"Failed to build driver roster export: {e}", exc_info=True)
        _capture_export_failure("driver_roster", e)
        metrics.inc(
            "spinr_admin_compliance_export_total",
            {"report_type": "driver_roster", "outcome": "error"},
        )
        raise HTTPException(status_code=503, detail="Compliance report data unavailable — database error") from e

    fieldnames = ["driver_name", "license_number", "license_class", "status", "onboarded_at"]
    subtitle = f"Status: {status}" if status else "All statuses"
    # State the exclusion on the page itself — an insurer reading this needs to
