def _q2(v: Any) -> Decimal:
    """Quantize a money value to 2dp (HALF_UP). Decimal-only — never float."""
    return Decimal(str(v or 0)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


async def _authoritative_ride_charge(ride_id: str, rider_id: str, tip_amount: Decimal) -> Decimal:
    """Server-authoritative amount the rider owes for a ride: grand_total + tip.

    ``grand_total`` already includes area/booking fees and GST/PST; ``total_fare``
    is only the fare-side subtotal. We compute the charge here rather than
    trusting the client-supplied amount so the Stripe (create-intent /
    payment-sheet) paths can never undercharge by omitting fees or tax — the
    same total ``/rides/{id}/process-payment`` settles. Falls back to
    ``total_fare`` only for legacy rides written before ``grand_total`` existed.
    """
    ride = await db_supabase.get_ride(ride_id)
    if not ride:
        raise HTTPException(status_code=404, detail="Ride not found")
    if ride.get("rider_id") != rider_id:
        raise HTTPException(status_code=403, detail="Not authorized to pay for this ride")
    # Explicit None check, not truthiness: a legitimate $0 grand_total (comp /
    # fully-covered ride) must NOT fall through to a non-zero total_fare and
    # overcharge. Only fall back when grand_total was never written (legacy).
    grand_raw = ride.get("grand_total")
    if grand_raw is None:
        grand_raw = ride.get("total_fare", 0)
    grand = _q2(grand_raw)
    return _q2(grand + _q2(tip_amount))


class PaymentIntentRequest(BaseModel):
    """Request body for POST /payments/create-intent."""

    amount: Decimal = Field(..., gt=0, le=100000, decimal_places=2, description="Amount in CAD (1–100000)")
    ride_id: Optional[str] = None
    # Tip is added on top of the ride's grand_total when ride_id is present.
    # For ride payments the server computes the charge as grand_total + tip and
    # ignores `amount` (advisory only) — see _authoritative_ride_charge.
    tip_amount: Decimal = Field(0, ge=0, le=500, decimal_places=2)
    # UUID v4 generated by the mobile client for each new payment attempt.
    # Prevents Stripe idempotency-key collisions when the same user pays
    # the same fare amount on two separate rides within the same 24 h window.
    client_idempotency_key: Optional[str] = None
    payment_method_id: Optional[str] = None


class ConfirmPaymentRequest(BaseModel):
    """Request body for POST /payments/confirm.

    Typed (not a raw dict) so the pi_mock_* production guard and the
    ownership checks below operate on validated, length-bounded strings —
    unknown keys are rejected instead of silently carried along.
    """

    model_config = {"extra": "forbid"}

    payment_intent_id: Optional[str] = Field(None, min_length=1, max_length=255)
    ride_id: Optional[str] = Field(None, min_length=1, max_length=64)


class PaymentSheetRequest(BaseModel):
    """Request body for POST /payments/payment-sheet."""

    amount: Decimal = Field(..., gt=0, le=100000, decimal_places=2, description="Fare amount in CAD")
    ride_id: Optional[str] = None
    # See PaymentIntentRequest.tip_amount — server charges grand_total + tip
    # for ride payments and treats `amount` as advisory.
    tip_amount: Decimal = Field(0, ge=0, le=500, decimal_places=2)
    client_idempotency_key: Optional[str] = None


# ── Stripe identity mode drift (test → live cutover) ──────────────────────
#
# `stripe_secret_key` lives in the app_settings DB table so it can be rotated
# without a redeploy (see CLAUDE.md). Rotating it ACROSS modes
# (`sk_test_…` → `sk_live_…`) silently invalidates every stored
# `users.stripe_customer_id`: Stripe scopes object IDs per mode, so the live
# key cannot see a test-mode customer and answers `resource_missing` on every
# call. Without repair the rider gets a hard 502 on the cards screen forever
# — and cannot add a replacement card either, because attaching one addresses
# the same dead customer.
#
# The rider's test-mode cards are NOT recoverable: they were test PANs and
# never existed as real cards, and Stripe offers no test→live copy path. So
# the honest outcome is a working, empty card list they can add a real card
# to — not a broken screen.
#
# Kill switch: set `stripe_reprovision_stale_ids = false` in app_settings
# (admin-editable, propagates within the 60 s settings cache, no redeploy).
_REPROVISION_FLAG = "stripe_reprovision_stale_ids"


async def _reprovision_stripe_customer(
    user_id: str,
    stale_customer_id: str,
    stripe_secret: str,
    reason: str,
) -> str:
    """Mint a fresh Stripe customer for ``user_id`` and archive the unusable one.

    Only ever called with positive proof that ``stale_customer_id`` is not
    reachable on the running key — either an explicit mode disagreement
    (``stale_by_mode``) or a ``resource_missing`` from Stripe itself
    (``is_missing_on_key``). It is never called on an authentication or
    transient error; ``utils/stripe_mode.py`` documents why that distinction
    is load-bearing (a bad key makes *every* object look missing).
    """
    settings = await get_app_settings()
    if not settings.get(_REPROVISION_FLAG, True):
        # Kill switch engaged: leave the row untouched and fail loudly rather
        # than serving a card list we already know addresses a dead customer.
        logger.error(
            "Stale Stripe customer detected but %s is off — not repairing",
            _REPROVISION_FLAG,
            extra={"user_id": user_id, "reason": reason},
        )
        raise HTTPException(
            status_code=503,
            detail="Your payment profile needs attention. Please contact support.",
        )

    mode = key_mode(stripe_secret)
    customer = await asyncio.to_thread(
        lambda: stripe.Customer.create(
            # PIPEDA (C4): still no email/name to Stripe — only the correlating
            # user_id, plus the superseded ID so the two can be reconciled
            # against the old account without a Spinr-side lookup.
            metadata={"user_id": user_id, "superseded_customer": stale_customer_id},
            api_key=stripe_secret,
            # Deliberately NOT the `cus-create-` key used for a first-time
            # create: replaying that one could hand back the very customer we
            # just proved unusable. Keying on the dead ID makes concurrent
            # healers and retries converge on ONE replacement.
            idempotency_key=f"cus-reprovision-{user_id}-{stale_customer_id}",
        )
    )

    # Conditional write: filtering on the stale value means a concurrent healer
    # that already landed a different customer is not clobbered.
    #
    # `default_payment_method` MUST be cleared in the same write. A `pm_…` is
    # scoped to the customer that owns it, so a token left behind would point
    # settlement (services/payment_service.py:966) and cancellation-fee capture
    # (routes/rides/cancellation.py) at a card that no longer exists — turning
    # a fixed cards screen into failed charges at trip end.
    await db_supabase.update_one(
        "users",
        {"id": user_id, "stripe_customer_id": stale_customer_id},
        {
            "stripe_customer_id": customer.id,
            "stripe_customer_id_mode": mode,
            "stripe_customer_id_superseded": stale_customer_id,
            "stripe_customer_id_superseded_at": datetime.now(timezone.utc).isoformat(),
            "default_payment_method": None,
        },
    )
    # Degraded-but-recovered → warning + metric, per the observability
    # conventions in CLAUDE.md. Stripe IDs are operational identifiers, not
    # PII, so they are safe to log; no email/phone/name appears here.
    logger.warning(
        "Re-provisioned Stripe customer after mode drift",
        extra={
            "user_id": user_id,
            "reason": reason,
            "superseded_customer_id": stale_customer_id,
            "new_customer_id": customer.id,
            "mode": mode,
        },
    )
    _metrics_inc("spinr_payments_stripe_identity_reprovisioned_total", {"surface": "rider", "reason": reason})

    # Re-read so a concurrent healer's winning value is what we return.
    fresh = await db_supabase.get_user_by_id(user_id)
    return (fresh or {}).get("stripe_customer_id") or customer.id


def _metrics_inc(name: str, labels: dict) -> None:
    """Best-effort counter. Metrics must never break a payment path."""
    try:
        try:
            from ..utils import metrics
        except ImportError:
            from utils import metrics  # type: ignore
        metrics.inc(name, labels)
    except Exception:  # pragma: no cover - defensive only
        logger.debug("metric %s not recorded", name, exc_info=True)


async def get_or_create_stripe_customer(user_id: str, stripe_secret: str):
    """Return the user's Stripe customer id, creating it on first use.

    Adds no Stripe round-trip for an existing customer. A row whose stamped
    mode disagrees with the running key is repaired here, from the stamp
    alone; an *unstamped* stale row (everything predating migration 286) is
    repaired the other way, by :func:`with_customer_repair` catching the
    ``resource_missing`` from the call that actually fails.
    """
    user = await db_supabase.get_user_by_id(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="User not found")

    stripe_customer_id = user.get("stripe_customer_id")

    if stripe_customer_id:
        # Cheap path: the row is stamped and the stamp disagrees with the key.
        # No Stripe call is needed to know the id is unusable.
        if stale_by_mode(user.get("stripe_customer_id_mode"), key_mode(stripe_secret)):
            return await _reprovision_stripe_customer(
                user_id, stripe_customer_id, stripe_secret, reason="mode_mismatch"
            )
        return stripe_customer_id

    # PIPEDA (C4): do NOT send the rider's email or legal name to Stripe (a
    # US processor). Neither is required to create a customer — only
    # metadata.user_id is needed to correlate the Stripe customer back to
    # our user. Avoiding the transfer keeps PII inside the Canadian region;
    # contact details can be attached later only if a specific Stripe flow
    # (e.g. a dispute) actually requires them.
    customer = await asyncio.to_thread(
        lambda: stripe.Customer.create(
            metadata={"user_id": user_id},
            api_key=stripe_secret,
            idempotency_key=f"cus-create-{user_id}",
        )
    )
    stripe_customer_id = customer.id
    # Stamp the mode from the object Stripe returned (its own `livemode`), not
    # from the key we sent — evidence over inference. This is what lets a
    # future key rotation be detected without a Stripe round-trip.
    await db_supabase.update_one(
        "users",
        {"id": user_id},
        {
            "stripe_customer_id": stripe_customer_id,
            "stripe_customer_id_mode": object_mode(customer) or key_mode(stripe_secret),
        },
    )
    # Re-read to use the authoritative value in case a concurrent replica wrote first.
    # (The loser's Stripe customer is unused but harmless; deduplication can run offline.)
    fresh = await db_supabase.get_user_by_id(user_id)
    if not fresh:
        raise HTTPException(status_code=404, detail="User not found during Stripe customer creation")
    # Never hand back a falsy customer id: callers pass it straight to Stripe,
    # where `customer=None` silently creates an unattached object rather than
    # erroring. Raising here keeps that invariant in one place instead of
    # repeating a defensive check at each call site.
    persisted = fresh.get("stripe_customer_id")
    if not persisted:
        logger.error("Stripe customer create persisted no id", extra={"user_id": user_id})
        raise HTTPException(status_code=502, detail="Could not set up payments. Please try again.")
    return persisted


async def with_customer_repair(user_id: str, stripe_secret: str, op):
    """Run ``await op(customer_id)``, repairing a stranded customer once.

    The repair trigger is the failure itself: if Stripe answers
    ``resource_missing`` for the customer we addressed, that id is not on this
    key (the test→live rotation case), so we mint a replacement and run ``op``
    against it. Any other error — auth, rate limit, connection, card decline —
    propagates untouched and writes nothing; see ``utils/stripe_mode.py`` for
    why that line matters.

    Costs nothing on the healthy path: no extra round-trip, no extra read.
    """
    customer_id = await get_or_create_stripe_customer(user_id, stripe_secret)
    try:
        return customer_id, await op(customer_id)
    except Exception as e:
        if not is_missing_on_key(e, customer_id):
            raise
        repaired = await _reprovision_stripe_customer(
            user_id, customer_id, stripe_secret, reason="resource_missing"
        )
        # One retry only. If the fresh customer also 404s, something is wrong
        # with the key or the account, not with this row — let it surface.
        return repaired, await op(repaired)


@api_router.post("/create-intent")
@payment_action_limit
@idempotent_endpoint(scope="payment_intent")
async def create_payment_intent(
    body: PaymentIntentRequest,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Create a Stripe payment intent.

    `amount` is validated by Pydantic (positive, ≤ 100000 CAD) before we
    reach Stripe. Rejecting at the boundary gives a 422 response on bad
    input instead of a 500 after Stripe refuses it.
    """
    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")

    if not stripe_secret:
        raise HTTPException(
            status_code=503,
            detail="Payment processing is not configured. Please contact support.",
        )

    try:
        # For ride payments the server is authoritative on the amount: charge
        # grand_total + tip (the full rider-owed total incl. area fees + GST/PST),
        # not the client-supplied figure. This closes an undercharge where the
        # client sent only total_fare (fare minus fees/tax) and the tax went
        # uncollected — and mirrors what /rides/{id}/process-payment settles.
        charge_amount = Decimal(str(body.amount))
        if body.ride_id:
            charge_amount = await _authoritative_ride_charge(body.ride_id, current_user["id"], body.tip_amount)

        # Decimal-safe dollars→cents (HALF_UP). ``int(amount * 100)``
        # would undercharge by 1¢ on values like $0.29, $1.13, $17.81 due
        # to binary-float drift. See backend/utils/money.py.
        amount = dollars_to_cents(charge_amount)

        intent_params = {
            "amount": amount,
            "currency": "cad",
            "automatic_payment_methods": {"enabled": True},
            "metadata": {"user_id": current_user["id"], "ride_id": body.ride_id or ""},
        }

        if body.payment_method_id:
            intent_params["payment_method"] = body.payment_method_id

        # Idempotency key ties this PaymentIntent to a specific ride so a
        # network retry cannot create a duplicate charge (P2-8 / DV-4).
        # Priority: client-supplied UUID (most specific) > ride-scoped key
        # (safe: ride IDs are globally unique) > 1-minute time-bucket per user
        # (last resort when ride_id absent — prevents same-amount collisions
        # that occurred with the old "intent-{user}-{amount}" pattern).
        import time as _time

        if body.client_idempotency_key:
            idempotency_key = body.client_idempotency_key
        elif body.ride_id:
            # Include the charge amount (cents) so that if the rider changes
            # their tip and retries, Stripe sees a distinct key and creates a
            # fresh PaymentIntent instead of raising IdempotencyError on the
            # amount mismatch. Same amount → same key → still idempotent.
            idempotency_key = f"ride-{body.ride_id}-{current_user['id']}-{amount}"
        else:
            idempotency_key = f"intent-{current_user['id']}-{int(_time.time() // 60)}"
        # Sync Stripe SDK: threadpool so the round-trip doesn't block the
        # event loop (idempotency key makes retries safe).
        #
        # Wrapped in the repair helper because this is the authoritative
        # ride-charge path: a rider whose customer was stranded by a key
        # rotation and who never opened the cards screen (so was never healed
        # there) would otherwise hit a hard failure at trip end, with a
        # completed ride and no way to pay for it. The idempotency key carries
        # the customer so the repaired retry cannot collide with the first
        # attempt's key.
        async def _create_intent(cid: str):
            return await asyncio.to_thread(
                lambda: stripe.PaymentIntent.create(
                    **{**intent_params, "customer": cid},
                    api_key=stripe_secret,
                    idempotency_key=f"{idempotency_key}-{cid}",
                )
            )

        _customer_id, intent = await with_customer_repair(current_user["id"], stripe_secret, _create_intent)

        # 3-D Secure / SCA happy-path: PaymentIntent succeeded at the API
        # boundary but Stripe is asking the rider to complete an additional
        # authentication step (3DS challenge). The mobile SDK reads
        # `client_secret` + `next_action` to drive the flow. We surface this
        # as a 402 with `code='action_required'` so the rider app branches
        # into Stripe's handleNextAction() rather than treating it as
        # success and confirming the payment server-side.
        if getattr(intent, "status", None) == "requires_action":
            return JSONResponse(
                status_code=402,
                content={
                    "success": False,
                    "detail": "Additional authentication required",
                    "error": {
                        "code": ErrorCode.PAYMENT_METHOD_INVALID.value,
                        "message": "Additional authentication required",
                        "message_key": ErrorKeys.PAYMENT_METHOD_INVALID,
                        "details": {
                            "code": "action_required",
                            "client_secret": intent.client_secret,
                            "payment_intent_id": intent.id,
                            "next_action": getattr(intent, "next_action", None),
                        },
                    },
                },
            )

        return {
            "client_secret": intent.client_secret,
            "payment_intent_id": intent.id,
            "mock": False,
        }
    except stripe.error.CardError as e:
        # Order matters: CardError must come BEFORE the generic StripeError
        # branch (Python checks except clauses top-down, and CardError is a
        # StripeError subclass). Card-decline / wrong-CVC / expired-card all
        # land here and must surface as 402 so the rider SDK switches to
        # the "try another card" UX. 3-D Secure challenges raised
        # synchronously (rare; the success-path handler above is the common
        # route) appear as code='authentication_required' and we forward
        # that to the SDK as code='action_required'.
        logger.error(f"Stripe CardError on create-intent: {e}", exc_info=True)
        details: Dict[str, Any] = {}
        if getattr(e, "code", None) == "authentication_required":
            details["code"] = "action_required"
        raise PaymentMethodInvalidException(
            message=getattr(e, "user_message", None) or "Card declined",
            message_key=ErrorKeys.PAYMENT_METHOD_INVALID,
            status_code=402,
            action_hint="Add a different card",
            details=details or None,
        ) from e
    except stripe.error.RateLimitError as e:
        # Stripe is throttling us. 429 with Retry-After lets the rider
        # app's Axios interceptor back off rather than retrying instantly.
        # We use SpinrException directly (not RateLimitExceededException)
        # to keep the response shape identical to the OTP-lockout 429
        # handler — same parser on the mobile side.
        logger.error(f"Stripe RateLimitError on create-intent: {e}", exc_info=True)
        raise SpinrException(
            message="Payment provider is rate-limiting requests. Please try again shortly.",
            error_code=ErrorCode.RATE_LIMIT_EXCEEDED,
            status_code=429,
            headers={"Retry-After": "30"},
            action_hint="Try again in a moment",
        ) from e
    except stripe.error.StripeError as e:
        logger.error(f"Stripe API error on create-intent: {e}", exc_info=True)
        raise HTTPException(status_code=502, detail="Payment service unavailable. Please try again.") from e
    except HTTPException:
        # Intentional 4xx (ownership 403, validation 400) from helpers like
        # _authoritative_ride_charge must reach the client, not become a 500.
        raise
    except Exception as e:
        logger.error(f"Unexpected error on create-intent: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e


@api_router.post("/confirm")
@payment_action_limit
@idempotent_endpoint(scope="payment_confirm")
async def confirm_payment(
    body: ConfirmPaymentRequest,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Confirm payment was successful"""
    payment_intent_id = body.payment_intent_id
    ride_id = body.ride_id

    # Mock-payment shortcut is allowed only outside production, OR for an
    # allow-listed app-store reviewer account (so a reviewer can reach a "paid"
    # confirmation without a real charge). Reject everyone else up front —
    # before claiming the ride into payment_status=processing — so a rejected
    # request can't strand the ride. In production any other authenticated rider
    # could otherwise send "pi_mock_*" and settle their own ride for free.
    _is_reviewer = current_user.get("phone") in core_settings.review_login_map()
    if (
        payment_intent_id
        and payment_intent_id.startswith("pi_mock_")
        and core_settings.ENV.lower() == "production"
        and not _is_reviewer
    ):
        logger.error(
            "Rejected mock payment intent %s in production for ride %s",
            payment_intent_id,
            ride_id,
        )
        raise HTTPException(
            status_code=400,
            detail="Mock payments are not supported in production",
        )

    is_mock = bool(payment_intent_id and payment_intent_id.startswith("pi_mock_"))
    # Bound unconditionally so the Stripe call below never references an unbound
    # name; the real value is assigned in the non-mock processor gate, which 503s
    # if it is still empty (so this default never reaches stripe.PaymentIntent).
    stripe_secret = ""

    if ride_id:
        ride = await db_supabase.get_ride(ride_id)
        if not ride:
            raise HTTPException(status_code=404, detail="Ride not found")
        if ride["rider_id"] != current_user["id"]:
            raise HTTPException(status_code=403, detail="forbidden")

        # C-3: Idempotency check — if a prior webhook already settled this payment,
        # return early with a clear signal rather than re-entering the Stripe flow.
        # This covers the case where the rider app retries confirm_payment after a
        # network timeout when the webhook has already processed the payment.
        # HTTP 200 (not 409) because the payment succeeded — this is not an error.
        payment_status = ride.get("payment_status")
        if payment_status in ("paid", "processing"):
            logger.info(
                "confirm_payment: ride %s already in payment_status=%s, returning early (C-3 idempotency)",
                ride_id,
                payment_status,
            )
            return {"status": "already_processed", "payment_status": payment_status}

    # Processor-availability gate (C1): a non-mock confirm with no Stripe secret
    # must NOT settle a ride. The key can be transiently empty during rotation;
    # returning a success shape would mark a ride paid with no real charge.
    # Placed AFTER ownership/idempotency (a non-owner still gets 403) but BEFORE
    # the claim, so a transiently-empty key can't strand the ride in
    # payment_status='processing'. Mirrors create_payment_intent's 503.
    if not is_mock:
        settings = await get_app_settings()
        stripe_secret = settings.get("stripe_secret_key", "")
        if not stripe_secret:
            raise HTTPException(
                status_code=503,
                detail="Payment processing is not configured. Please contact support.",
            )

    if ride_id:
        claimed = await db_supabase.claim_ride_payment_processing(ride_id)
        if not claimed:
            raise HTTPException(status_code=409, detail="payment_already_processing")

    # Mock-payment shortcut (non-production only; production rejected above).
    if is_mock:
        if ride_id:
            _ride = await db_supabase.get_ride(ride_id)
            if not _ride or _ride.get("rider_id") != current_user["id"]:
                raise HTTPException(
                    status_code=403,
                    detail="Not authorized to confirm payment for this ride",
                )
            await db_supabase.update_ride(
                ride_id,
                {"payment_status": "paid", "payment_intent_id": payment_intent_id},
            )
        return {"status": "succeeded", "mock": True}

    # Non-mock path: stripe_secret is guaranteed non-empty (gated above), so we
    # never reach the old success-shaped fallback — a missing processor already
    # raised 503 before the claim.
    try:
        intent = await asyncio.to_thread(
            lambda: stripe.PaymentIntent.retrieve(payment_intent_id, api_key=stripe_secret)
        )

        if intent.metadata.get("user_id") != str(current_user["id"]):
            raise HTTPException(status_code=403, detail="Not authorized to confirm this payment")

        if ride_id:
            _ride = await db_supabase.get_ride(ride_id)
            if not _ride or _ride.get("rider_id") != current_user["id"]:
                raise HTTPException(
                    status_code=403,
                    detail="Not authorized to confirm payment for this ride",
                )

            # SECURITY (C1): ownership alone is insufficient — a rider owns
            # many PaymentIntents. Bind the PI to THIS ride and verify it
            # actually covers the owed total, or a rider could confirm a
            # cheap / other-ride intent against an expensive ride and underpay.
            pi_ride_id = (intent.metadata or {}).get("ride_id")
            if pi_ride_id and pi_ride_id != ride_id:
                logger.error(
                    "[confirm][security] PI %s metadata ride_id=%s != ride %s",
                    payment_intent_id,
                    pi_ride_id,
                    ride_id,
                )
                raise HTTPException(status_code=403, detail="Payment does not match this ride")

            # Only a genuinely succeeded charge can mark a ride paid, and only
            # when the captured amount covers the authoritative owed total
            # (grand_total). amount_received is 0 until the PI succeeds.
            if intent.status == "succeeded":
                _grand = _ride.get("grand_total")
                if _grand is None:
                    _grand = _ride.get("total_fare", 0)
                owed_cents = int((_q2(_grand) * 100).to_integral_value())
                received = int(getattr(intent, "amount_received", 0) or 0)
                if received < owed_cents:
                    logger.error(
                        "[confirm][security] underpay ride=%s pi=%s received=%d owed=%d",
                        ride_id,
                        payment_intent_id,
                        received,
                        owed_cents,
                    )
                    raise HTTPException(
                        status_code=402,
                        detail={
                            "code": "AMOUNT_MISMATCH",
                            "message": "Payment amount does not cover the fare.",
                        },
                    )

            await db_supabase.update_ride(
                ride_id,
                {
                    "payment_status": intent.status,
                    "payment_intent_id": payment_intent_id,
                },
            )

        return {"status": intent.status, "mock": False}
    except HTTPException:
        # Ownership 403s above must reach the client, not become a 500.
        raise
    except Exception as e:
        logger.error(f"Stripe error: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e


