"""
Unit tests for backend/utils/insurance_periods.py and the open_period
call-sites in backend/routes/drivers.py.

Coverage:
    1. open_period closes any existing open row via update_one.
    2. open_period inserts the new period row with correct fields.
    3. open_period works when there is no existing open row (no update_one call).
    4. open_period with period=2 and no ride_id: row is still inserted (non-fatal).
    5. open_period swallows DB errors — never raises to the caller.
    6. go-online (update_driver_status is_online=True) calls open_period(period=1).
    7. go-offline (update_driver_status is_online=False) calls open_period(period=0).
    8. complete_ride calls open_period(period=1) after the ride is completed.
"""

from __future__ import annotations

from unittest.mock import AsyncMock, MagicMock, patch

import pytest

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

DRIVER_ID = "driver-abc-123"
RIDE_ID = "ride-xyz-456"
TABLE = "driver_insurance_periods"


# ---------------------------------------------------------------------------
# Tests for open_period utility (utils/insurance_periods.py)
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_open_period_closes_existing_open_row():
    """When an open row exists it must be closed via update_one before insert."""
    open_row = {"id": "period-row-old", "driver_id": DRIVER_ID, "period": 1, "ended_at": None}

    mock_get_rows = AsyncMock(return_value=[open_row])
    mock_update_one = AsyncMock(return_value=None)
    mock_insert_one = AsyncMock(return_value={"id": "period-row-new"})

    with (
        patch("utils.insurance_periods.get_rows", mock_get_rows),
        patch("utils.insurance_periods.update_one", mock_update_one),
        patch("utils.insurance_periods.insert_one", mock_insert_one),
    ):
        from utils.insurance_periods import open_period

        await open_period(DRIVER_ID, 1)

    # Must have queried for open rows for this driver.
    mock_get_rows.assert_awaited_once_with(TABLE, {"driver_id": DRIVER_ID, "ended_at": None}, limit=5)

    # Must have closed the existing open row.
    mock_update_one.assert_awaited_once()
    _, update_filters, update_payload = mock_update_one.call_args[0]
    assert update_filters == {"id": "period-row-old"}
    assert "ended_at" in update_payload


@pytest.mark.anyio
async def test_open_period_inserts_new_row():
    """After closing existing rows, open_period inserts the new period row."""
    open_row = {"id": "period-row-old", "driver_id": DRIVER_ID, "period": 1, "ended_at": None}

    mock_get_rows = AsyncMock(return_value=[open_row])
    mock_update_one = AsyncMock(return_value=None)
    mock_insert_one = AsyncMock(return_value={"id": "period-row-new"})

    with (
        patch("utils.insurance_periods.get_rows", mock_get_rows),
        patch("utils.insurance_periods.update_one", mock_update_one),
        patch("utils.insurance_periods.insert_one", mock_insert_one),
    ):
        from utils.insurance_periods import open_period

        await open_period(DRIVER_ID, 2, ride_id=RIDE_ID)

    mock_insert_one.assert_awaited_once()
    insert_table, insert_payload = mock_insert_one.call_args[0]
    assert insert_table == TABLE
    assert insert_payload["driver_id"] == DRIVER_ID
    assert insert_payload["period"] == 2
    assert insert_payload["ride_id"] == RIDE_ID
    assert "started_at" in insert_payload
    assert "id" in insert_payload  # uuid generated by open_period


@pytest.mark.anyio
async def test_open_period_with_no_existing_row():
    """When no open row exists, open_period skips update_one and still inserts."""
    mock_get_rows = AsyncMock(return_value=[])
    mock_update_one = AsyncMock(return_value=None)
    mock_insert_one = AsyncMock(return_value={"id": "period-row-new"})

    with (
        patch("utils.insurance_periods.get_rows", mock_get_rows),
        patch("utils.insurance_periods.update_one", mock_update_one),
        patch("utils.insurance_periods.insert_one", mock_insert_one),
    ):
        from utils.insurance_periods import open_period

        await open_period(DRIVER_ID, 0)

    mock_update_one.assert_not_awaited()

    mock_insert_one.assert_awaited_once()
    _, insert_payload = mock_insert_one.call_args[0]
    assert insert_payload["period"] == 0
    assert insert_payload["driver_id"] == DRIVER_ID


@pytest.mark.anyio
async def test_open_period_period_2_no_ride_id_still_inserts():
    """period=2 with ride_id=None is non-fatal — row is inserted with ride_id=None."""
