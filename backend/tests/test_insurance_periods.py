@pytest.mark.anyio
async def test_open_period_db_error_does_not_raise():
    """If get_rows raises, open_period logs the error and does NOT propagate."""
    mock_get_rows = AsyncMock(side_effect=RuntimeError("DB connection refused"))

    with (
        patch("utils.insurance_periods.get_rows", mock_get_rows),
        patch("utils.insurance_periods.logger") as mock_logger,
    ):
        from utils.insurance_periods import open_period

        # Must complete without raising.
        await open_period(DRIVER_ID, 1)

    mock_logger.error.assert_called_once()
    error_first_arg = mock_logger.error.call_args[0][0]
    assert "failed" in error_first_arg.lower() or "INSURANCE" in error_first_arg


