"""Admin Compliance & Tax Reporting — regulatory/tax exports that aren't
covered by operational analytics (routes/admin/analytics.py) or the
fixed-format SGI forms (routes/admin/sgi_forms.py).

Every report generated here is:
  - Spinr-branded (backend/utils/report_branding.py), never a regulator's
    own fixed layout — fixed-format documents (SGI D00032/D00033, future
    equivalents) are generated by sgi_form_filler instead.
  - Logged to compliance_export_events (migration 263) for audit trail —
    who pulled which report, when, over what params.

Money arithmetic is Decimal-only per CLAUDE.md — never float.
"""

