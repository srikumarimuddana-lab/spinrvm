/**
 * render-voltra-templates.mjs — build-time generator for the iOS Live Activity
 * push templates (Phase 3, Option C). Renders VoltraRideActivity over the
 * (status x eta-bucket) grid into backend/utils/voltra_templates.json, which the
 * Python backend (backend/utils/apns_client.py) indexes and pushes via APNs.
 *
 * Run from rider-app/ AFTER `yarn install` (needs @use-voltra/ios-server):
 *     node scripts/render-voltra-templates.mjs
 * Re-run + commit on any change to VoltraRideActivity.tsx (wire a CI drift check
 * so the committed JSON can't go stale vs the component).
 *
 * Pushed templates are GENERIC by design (no per-ride driver name / vehicle /
 * exact area — those can't be pre-rendered): the rich, ride-specific content
 * shows on-device via autoUpdate while the app is alive; the locked/killed screen
 * shows status + ETA bucket. The on-device Voltra.Timer counts down between
 * buckets so ETA stays live without a push per minute.
 *
 * ⚠️ BUILD-TIME VERIFY: the renderLiveActivityToString import + signature below
 * are from the Phase 3 research synthesis and MUST be confirmed against the
 * installed @use-voltra/ios-server before relying on the output. The grid, keys,
 * headlines, and output path are the stable contract.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// VERIFY: exact export name/signature against installed @use-voltra/ios-server.
import { renderLiveActivityToString } from '@use-voltra/ios-server';
import VoltraRideActivity from '../components/VoltraRideActivity.tsx';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '../../backend/utils/voltra_templates.json');

// Must match backend/utils/live_activity._headline and apns_client._eta_bucket.
const HEADLINE = {
    driver_accepted: 'Driver on the way',
    driver_arrived: 'Your driver has arrived',
    in_progress: 'On your way',
    completed: 'Trip complete',
    cancelled: 'Ride cancelled',
};
// Representative minutes per apns_client._eta_bucket key (null => 'none').
const ETA_BUCKETS = { none: null, lt2: 1, lt5: 4, lt10: 8, lt20: 15, gte20: 25 };

const out = {
    _meta: 'Generated by rider-app/scripts/render-voltra-templates.mjs — do not hand-edit.',
};
for (const [status, headline] of Object.entries(HEADLINE)) {
    for (const [bucket, etaMinutes] of Object.entries(ETA_BUCKETS)) {
        const content = { status, headline, etaMinutes };
        // VERIFY signature: (element) -> uiJsonData string.
        out[`${status}:${bucket}`] = renderLiveActivityToString(VoltraRideActivity(content));
    }
}

writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote ${Object.keys(out).length - 1} templates -> ${OUT}`);
