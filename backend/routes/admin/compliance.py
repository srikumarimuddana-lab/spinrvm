# ── Airport Trips ──────────────────────────────────────────────────
#
# Airport ground-transportation programs (the common pattern across North
# American airport authorities that permit TNC pickup/drop-off — this
# report follows that general convention, not a specific published spec
# from any one Saskatchewan airport authority, since none was available
# to confirm exact field requirements against) invoice Spinr per trip,
# usually with pickups and dropoffs billed as separate line items. This
# report exists to reconcile that invoice, so every field the authority
# needs to verify a trip count is included: date/time, whether the trip
# was an airport PICKUP (revenue-generating — usually what the per-trip
# fee is based on) or an airport DROPOFF, rider name, driver name, the
# driver's vehicle registration (make/model/color + license plate — some
# authorities require this on file per trip), pickup/dropoff points,
# distance, and which service area (city) the airport is in. The
# pickup/dropoff counts are also broken out in the report subtitle so an
# admin doesn't have to re-tally trip_type by hand before sending it to
# the airport. Matched by a simple text search on pickup/dropoff address
# rather than a dedicated "is this an airport" flag — Spinr's venues
# table already curates "Airport" as a named pickup venue
# (routes/admin/venues.py), but rides store free-text geocoded addresses,
# not a venue_id foreign key, so address matching is what's actually
# queryable today.


async def _airport_trips_rows(
    start_date: datetime, end_date: datetime, service_area_ids: Optional[list[str]] = None
) -> tuple[list[dict], bool]:
    """Airport trips for an airport authority's per-trip invoice.

    `service_area_ids` scopes the report; `None` means every area. Each airport
    authority bills only its own airport, so exporting every area at once hands
    one authority another airport's trips. Selecting a city automatically
    includes its airport sub-area (`_expand_service_area_ids`), which is what
    you want here — a "Calgary" scope should cover YYC.
    """
    rides = await db_supabase.get_rows(
        "rides",
        {
            "status": "completed",
            "ride_completed_at": {"$gte": start_date.isoformat(), "$lte": end_date.isoformat()},
        },
        columns="id,rider_id,driver_id,service_area_id,pickup_address,dropoff_address,distance_km,ride_completed_at",
        limit=_ROW_LIMIT,
    )
    airport_rides = [
        r
        for r in rides
        if "airport" in (r.get("pickup_address") or "").lower() or "airport" in (r.get("dropoff_address") or "").lower()
    ]
    if service_area_ids:
        allowed_areas = await _expand_service_area_ids(service_area_ids)
        airport_rides = [r for r in airport_rides if r.get("service_area_id") in allowed_areas]
    truncated = _check_truncated(len(rides), "airport_trips")
    if not airport_rides:
        return [], truncated

    driver_ids = sorted({r["driver_id"] for r in airport_rides if r.get("driver_id")})
    driver_names: dict[str, str] = {}
    driver_vehicles: dict[str, str] = {}
    for i in range(0, len(driver_ids), 200):
        batch = driver_ids[i : i + 200]
        driver_rows = await db_supabase.get_rows(
            "drivers",
            {"id": {"$in": batch}},
            columns="id,name,first_name,last_name,license_plate,vehicle_make,vehicle_model,vehicle_color",
            limit=len(batch),
        )
        for d in driver_rows:
            driver_names[d["id"]] = (
                d.get("name") or f"{d.get('first_name', '')} {d.get('last_name', '')}".strip() or d["id"]
            )
            vehicle_desc = " ".join(
                part for part in (d.get("vehicle_color"), d.get("vehicle_make"), d.get("vehicle_model")) if part
            )
            plate = d.get("license_plate") or ""
            driver_vehicles[d["id"]] = f"{vehicle_desc} — {plate}".strip(" —") if vehicle_desc or plate else ""

    rider_ids = sorted({r["rider_id"] for r in airport_rides if r.get("rider_id")})
    rider_names: dict[str, str] = {}
    for i in range(0, len(rider_ids), 200):
        batch = rider_ids[i : i + 200]
        rider_rows = await db_supabase.get_rows(
            "users", {"id": {"$in": batch}}, columns="id,first_name,last_name", limit=len(batch)
        )
        for u in rider_rows:
            rider_names[u["id"]] = f"{u.get('first_name', '')} {u.get('last_name', '')}".strip() or u["id"]

    area_ids = sorted({r["service_area_id"] for r in airport_rides if r.get("service_area_id")})
    area_names: dict[str, str] = {}
    if area_ids:
        area_rows = await db_supabase.get_rows(
            "service_areas", {"id": {"$in": area_ids}}, columns="id,name", limit=len(area_ids)
        )
        area_names = {a["id"]: a.get("name") or a["id"] for a in area_rows}

    rows = []
    for r in airport_rides:
        pickup_is_airport = "airport" in (r.get("pickup_address") or "").lower()
        dropoff_is_airport = "airport" in (r.get("dropoff_address") or "").lower()
        trip_type = (
            "Both"
            if pickup_is_airport and dropoff_is_airport
            else ("Airport Pickup" if pickup_is_airport else "Airport Dropoff")
        )
        rows.append(
            {
                "date": report_branding.format_report_timestamp(r.get("ride_completed_at")),
                "trip_type": trip_type,
                "pickup_address": r.get("pickup_address") or "",
                "dropoff_address": r.get("dropoff_address") or "",
                "distance_km": f"{_d(r.get('distance_km')):.2f}",
                "rider_name": rider_names.get(r.get("rider_id"), r.get("rider_id") or ""),
                "driver_name": driver_names.get(r.get("driver_id"), r.get("driver_id") or ""),
                "vehicle": driver_vehicles.get(r.get("driver_id"), ""),
                "service_area": area_names.get(r.get("service_area_id"), ""),
            }
        )
    rows.sort(key=lambda row: row["date"], reverse=True)
    return rows, truncated


@api_router.get("/airport-trips")
@limiter.limit("10/minute")
async def get_airport_trips(
    request: Request,
    date_from: Optional[str] = Query(None, description="YYYY-MM-DD; defaults to the 1st of the current month"),
    date_to: Optional[str] = Query(None, description="YYYY-MM-DD; defaults to today"),
    format: str = Query("pdf", pattern="^(pdf|csv|xlsx|docx)$"),
    service_area_ids: Optional[str] = Query(
        None,
        description=(
            "Comma-separated service_area ids to scope the report to. Child sub-areas "
            "(e.g. a city's airport zone) are included automatically. Omit for every area."
        ),
    ),
    admin: dict = Depends(get_admin_user),
):
    """Completed rides with "airport" in the pickup or dropoff address —
    date/time, trip type (pickup/dropoff/both), rider, driver, vehicle
    registration, pickup/dropoff points, distance, and service area — for
    the airport authority to invoice Spinr per trip (pickups and dropoffs
    are billed separately by most authorities, so trip_type and the
    pickup/dropoff counts in the subtitle exist specifically to support
    that reconciliation). Spinr-branded; not any specific airport
    authority's fixed form (see module docstring for why: general
    TNC-airport reporting convention, not a confirmed published spec)."""
    start_date, end_date = _resolve_date_window(date_from, date_to)
    area_ids = _parse_service_area_ids(service_area_ids)

    try:
        rows, truncated = await _airport_trips_rows(start_date, end_date, area_ids)
    except Exception as e:
        logger.error(f"Failed to build airport trips report: {e}", exc_info=True)
        _capture_export_failure("airport_trips", e)
        metrics.inc("spinr_admin_compliance_export_total", {"report_type": "airport_trips", "outcome": "error"})
        raise HTTPException(status_code=503, detail="Compliance report data unavailable — database error") from e

    gate_response = await _check_export_gate(
        admin,
        "compliance.airport_trips",
        {"date_from": date_from, "date_to": date_to, "format": format, "service_area_ids": service_area_ids},
        len(rows),
    )
    if gate_response is not None:
        return gate_response

    fieldnames = [
        "date",
        "trip_type",
        "rider_name",
        "driver_name",
        "vehicle",
        "pickup_address",
        "dropoff_address",
        "distance_km",
        "service_area",
    ]
    total_km = sum((Decimal(r["distance_km"]) for r in rows), Decimal("0"))
    # Most airport authorities charge per-trip, pickup and dropoff counted
    # separately (a "Both" trip touches the airport twice) — broken out
    # here so the authority's invoice can be reconciled against the exact
    # count this report says, not just a total row count.
    pickup_count = sum(1 for r in rows if r["trip_type"] in ("Airport Pickup", "Both"))
    dropoff_count = sum(1 for r in rows if r["trip_type"] in ("Airport Dropoff", "Both"))
    subtitle = [
        report_branding.period_label(start_date, end_date),
        f"{len(rows)} trip(s)  ·  {pickup_count} pickup(s)  ·  {dropoff_count} dropoff(s)  ·  {total_km:.2f} total km",
    ]
    if truncated:
        subtitle[-1] += f" — ⚠ TRUNCATED at {_ROW_LIMIT} rides scanned; narrow the date range"

    await _log_compliance_export(
        admin, "airport_trips", {"date_from": date_from, "date_to": date_to, "format": format}, len(rows)
    )
    metrics.inc("spinr_admin_compliance_export_total", {"report_type": "airport_trips", "outcome": "success"})

    resp = _render_tabular_report(
        title="Airport Trips Report",
        filename_base="airport_trips",
        fieldnames=fieldnames,
        rows=rows,
        subtitle=subtitle,
        format=format,
        pdf_landscape=True,
        pdf_col_widths=[1.5, 1.3, 1.5, 1.5, 1.8, 2.0, 2.0, 1.0, 1.3],
    )
    return resp
