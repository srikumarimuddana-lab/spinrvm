DRIVER_USER_ID = "user-driver-001"
DRIVER_ROW = {
    "id": DRIVER_ID,
    "user_id": DRIVER_USER_ID,
    "name": "Test Driver",
    "status": "active",
    "is_verified": True,
    "is_online": False,
    "is_available": False,
}
DRIVER_ROW_ONLINE = {**DRIVER_ROW, "is_online": True, "is_available": True}


@pytest.mark.anyio
async def test_period_transition_go_online():
    """Going online must call open_period(driver_id, period=1)."""
    from backend.routes import drivers as drv_mod

    mock_open_period = AsyncMock()

    with (
        patch(
            "backend.routes.drivers.db_supabase.get_driver_by_id",
            AsyncMock(side_effect=[DRIVER_ROW, DRIVER_ROW_ONLINE]),
        ),
        patch("backend.routes.drivers.db_supabase.get_rows", AsyncMock(return_value=[])),
        patch("backend.routes.drivers.db_supabase.update_one", AsyncMock()),
        patch("backend.routes.drivers.mark_present", AsyncMock()),
        patch("backend.routes.drivers.clear_presence", AsyncMock()),
        # Patch the source module so the lazy inline import picks up the mock.
        patch("utils.insurance_periods.open_period", mock_open_period),
    ):
        result = await drv_mod.update_driver_status(
            driver_id=DRIVER_ID,
            is_online=True,
            current_user={"id": DRIVER_USER_ID},
        )

    assert result["success"] is True
    mock_open_period.assert_awaited_once_with(DRIVER_ID, period=1)


