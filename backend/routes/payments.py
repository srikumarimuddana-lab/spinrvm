async def get_or_create_stripe_customer(user_id: str, stripe_secret: str):
    user = await db_supabase.get_user_by_id(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="User not found")

    stripe_customer_id = user.get("stripe_customer_id")

    if not stripe_customer_id:
        customer = stripe.Customer.create(
            email=user.get("email"),
            name=f"{user.get('first_name', '')} {user.get('last_name', '')}".strip(),
            metadata={"user_id": user_id},
            api_key=stripe_secret,
            idempotency_key=f"cus-create-{user_id}",
        )
        stripe_customer_id = customer.id
        await db_supabase.update_one("users", {"id": user_id}, {"stripe_customer_id": stripe_customer_id})
        # Re-read to use the authoritative value in case a concurrent replica wrote first.
        # (The loser's Stripe customer is unused but harmless; deduplication can run offline.)
        fresh = await db_supabase.get_user_by_id(user_id)
        if not fresh:
            raise HTTPException(status_code=404, detail="User not found during Stripe customer creation")
        stripe_customer_id = fresh["stripe_customer_id"]

    return stripe_customer_id


@api_router.post("/create-intent")
@payment_action_limit
@idempotent_endpoint(scope="payment_intent")
async def create_payment_intent(
    body: PaymentIntentRequest,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Create a Stripe payment intent.

    `amount` is validated by Pydantic (positive, ≤ 100000 CAD) before we
    reach Stripe. Rejecting at the boundary gives a 422 response on bad
    input instead of a 500 after Stripe refuses it.
    """
    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")

    if not stripe_secret:
        raise HTTPException(
            status_code=503,
            detail="Payment processing is not configured. Please contact support.",
        )

    try:
        # For ride payments the server is authoritative on the amount: charge
        # grand_total + tip (the full rider-owed total incl. area fees + GST/PST),
        # not the client-supplied figure. This closes an undercharge where the
        # client sent only total_fare (fare minus fees/tax) and the tax went
        # uncollected — and mirrors what /rides/{id}/process-payment settles.
        charge_amount = Decimal(str(body.amount))
        if body.ride_id:
            charge_amount = await _authoritative_ride_charge(body.ride_id, current_user["id"], body.tip_amount)

        # Decimal-safe dollars→cents (HALF_UP). ``int(amount * 100)``
        # would undercharge by 1¢ on values like $0.29, $1.13, $17.81 due
        # to binary-float drift. See backend/utils/money.py.
        amount = dollars_to_cents(charge_amount)

        # Get or create customer for saved payments
        stripe_customer_id = await get_or_create_stripe_customer(current_user["id"], stripe_secret)

        intent_params = {
            "amount": amount,
            "currency": "cad",
            "automatic_payment_methods": {"enabled": True},
            "metadata": {"user_id": current_user["id"], "ride_id": body.ride_id or ""},
        }

        if stripe_customer_id:
            intent_params["customer"] = stripe_customer_id

        if body.payment_method_id:
            intent_params["payment_method"] = body.payment_method_id

        # Idempotency key ties this PaymentIntent to a specific ride so a
        # network retry cannot create a duplicate charge (P2-8 / DV-4).
        # Priority: client-supplied UUID (most specific) > ride-scoped key
        # (safe: ride IDs are globally unique) > 1-minute time-bucket per user
        # (last resort when ride_id absent — prevents same-amount collisions
        # that occurred with the old "intent-{user}-{amount}" pattern).
        import time as _time

        if body.client_idempotency_key:
            idempotency_key = body.client_idempotency_key
        elif body.ride_id:
            # Include the charge amount (cents) so that if the rider changes
            # their tip and retries, Stripe sees a distinct key and creates a
            # fresh PaymentIntent instead of raising IdempotencyError on the
            # amount mismatch. Same amount → same key → still idempotent.
            idempotency_key = f"ride-{body.ride_id}-{current_user['id']}-{amount}"
        else:
            idempotency_key = f"intent-{current_user['id']}-{int(_time.time() // 60)}"
        intent = stripe.PaymentIntent.create(
            **intent_params,
            api_key=stripe_secret,
            idempotency_key=idempotency_key,
        )

        # 3-D Secure / SCA happy-path: PaymentIntent succeeded at the API
        # boundary but Stripe is asking the rider to complete an additional
        # authentication step (3DS challenge). The mobile SDK reads
        # `client_secret` + `next_action` to drive the flow. We surface this
        # as a 402 with `code='action_required'` so the rider app branches
        # into Stripe's handleNextAction() rather than treating it as
        # success and confirming the payment server-side.
        if getattr(intent, "status", None) == "requires_action":
            return JSONResponse(
                status_code=402,
                content={
                    "success": False,
                    "detail": "Additional authentication required",
                    "error": {
                        "code": ErrorCode.PAYMENT_METHOD_INVALID.value,
                        "message": "Additional authentication required",
                        "message_key": ErrorKeys.PAYMENT_METHOD_INVALID,
                        "details": {
                            "code": "action_required",
                            "client_secret": intent.client_secret,
                            "payment_intent_id": intent.id,
                            "next_action": getattr(intent, "next_action", None),
                        },
                    },
                },
            )

        return {
            "client_secret": intent.client_secret,
            "payment_intent_id": intent.id,
            "mock": False,
        }
    except stripe.error.CardError as e:
        # Order matters: CardError must come BEFORE the generic StripeError
        # branch (Python checks except clauses top-down, and CardError is a
        # StripeError subclass). Card-decline / wrong-CVC / expired-card all
        # land here and must surface as 402 so the rider SDK switches to
        # the "try another card" UX. 3-D Secure challenges raised
        # synchronously (rare; the success-path handler above is the common
        # route) appear as code='authentication_required' and we forward
        # that to the SDK as code='action_required'.
        logger.error(f"Stripe CardError on create-intent: {e}", exc_info=True)
        details: Dict[str, Any] = {}
        if getattr(e, "code", None) == "authentication_required":
            details["code"] = "action_required"
        raise PaymentMethodInvalidException(
            message=getattr(e, "user_message", None) or "Card declined",
            message_key=ErrorKeys.PAYMENT_METHOD_INVALID,
            status_code=402,
            action_hint="Add a different card",
            details=details or None,
        ) from e
    except stripe.error.RateLimitError as e:
        # Stripe is throttling us. 429 with Retry-After lets the rider
        # app's Axios interceptor back off rather than retrying instantly.
        # We use SpinrException directly (not RateLimitExceededException)
        # to keep the response shape identical to the OTP-lockout 429
        # handler — same parser on the mobile side.
        logger.error(f"Stripe RateLimitError on create-intent: {e}", exc_info=True)
        raise SpinrException(
            message="Payment provider is rate-limiting requests. Please try again shortly.",
            error_code=ErrorCode.RATE_LIMIT_EXCEEDED,
            status_code=429,
            headers={"Retry-After": "30"},
            action_hint="Try again in a moment",
        ) from e
    except stripe.error.StripeError as e:
        logger.error(f"Stripe API error on create-intent: {e}", exc_info=True)
        raise HTTPException(status_code=502, detail="Payment service unavailable. Please try again.") from e
    except HTTPException:
        # Intentional 4xx (ownership 403, validation 400) from helpers like
        # _authoritative_ride_charge must reach the client, not become a 500.
        raise
    except Exception as e:
        logger.error(f"Unexpected error on create-intent: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e


@api_router.post("/confirm")
@payment_action_limit
@idempotent_endpoint(scope="payment_confirm")
async def confirm_payment(
    body: ConfirmPaymentRequest,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Confirm payment was successful"""
    payment_intent_id = body.payment_intent_id
    ride_id = body.ride_id

    # Mock-payment shortcut is allowed only outside production, OR for an
    # allow-listed app-store reviewer account (so a reviewer can reach a "paid"
    # confirmation without a real charge). Reject everyone else up front —
    # before claiming the ride into payment_status=processing — so a rejected
    # request can't strand the ride. In production any other authenticated rider
    # could otherwise send "pi_mock_*" and settle their own ride for free.
    _is_reviewer = current_user.get("phone") in core_settings.review_login_map()
    if (
        payment_intent_id
        and payment_intent_id.startswith("pi_mock_")
        and core_settings.ENV.lower() == "production"
        and not _is_reviewer
    ):
        logger.error(
            "Rejected mock payment intent %s in production for ride %s",
            payment_intent_id,
            ride_id,
        )
        raise HTTPException(
            status_code=400,
            detail="Mock payments are not supported in production",
        )

    if ride_id:
        ride = await db_supabase.get_ride(ride_id)
        if not ride:
            raise HTTPException(status_code=404, detail="Ride not found")
        if ride["rider_id"] != current_user["id"]:
            raise HTTPException(status_code=403, detail="forbidden")

        # C-3: Idempotency check — if a prior webhook already settled this payment,
        # return early with a clear signal rather than re-entering the Stripe flow.
        # This covers the case where the rider app retries confirm_payment after a
        # network timeout when the webhook has already processed the payment.
        # HTTP 200 (not 409) because the payment succeeded — this is not an error.
        payment_status = ride.get("payment_status")
        if payment_status in ("paid", "processing"):
            logger.info(
                "confirm_payment: ride %s already in payment_status=%s, returning early (C-3 idempotency)",
                ride_id,
                payment_status,
            )
            return {"status": "already_processed", "payment_status": payment_status}

        claimed = await db_supabase.claim_ride_payment_processing(ride_id)
        if not claimed:
            raise HTTPException(status_code=409, detail="payment_already_processing")

    # Mock-payment shortcut (non-production only; production rejected above).
    if payment_intent_id and payment_intent_id.startswith("pi_mock_"):
        if ride_id:
            _ride = await db_supabase.get_ride(ride_id)
            if not _ride or _ride.get("rider_id") != current_user["id"]:
                raise HTTPException(
                    status_code=403,
                    detail="Not authorized to confirm payment for this ride",
                )
            await db_supabase.update_ride(
                ride_id,
                {"payment_status": "paid", "payment_intent_id": payment_intent_id},
            )
        return {"status": "succeeded", "mock": True}

    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")

    if stripe_secret:
        try:
            intent = stripe.PaymentIntent.retrieve(payment_intent_id, api_key=stripe_secret)

            if intent.metadata.get("user_id") != str(current_user["id"]):
                raise HTTPException(status_code=403, detail="Not authorized to confirm this payment")

            if ride_id:
                _ride = await db_supabase.get_ride(ride_id)
                if not _ride or _ride.get("rider_id") != current_user["id"]:
                    raise HTTPException(
                        status_code=403,
                        detail="Not authorized to confirm payment for this ride",
                    )

                # SECURITY (C1): ownership alone is insufficient — a rider owns
                # many PaymentIntents. Bind the PI to THIS ride and verify it
                # actually covers the owed total, or a rider could confirm a
                # cheap / other-ride intent against an expensive ride and underpay.
                pi_ride_id = (intent.metadata or {}).get("ride_id")
                if pi_ride_id and pi_ride_id != ride_id:
                    logger.error(
                        "[confirm][security] PI %s metadata ride_id=%s != ride %s",
                        payment_intent_id,
                        pi_ride_id,
                        ride_id,
                    )
                    raise HTTPException(status_code=403, detail="Payment does not match this ride")

                # Only a genuinely succeeded charge can mark a ride paid, and only
                # when the captured amount covers the authoritative owed total
                # (grand_total). amount_received is 0 until the PI succeeds.
                if intent.status == "succeeded":
                    _grand = _ride.get("grand_total")
                    if _grand is None:
                        _grand = _ride.get("total_fare", 0)
                    owed_cents = int((_q2(_grand) * 100).to_integral_value())
                    received = int(getattr(intent, "amount_received", 0) or 0)
                    if received < owed_cents:
                        logger.error(
                            "[confirm][security] underpay ride=%s pi=%s received=%d owed=%d",
                            ride_id,
                            payment_intent_id,
                            received,
                            owed_cents,
                        )
                        raise HTTPException(
                            status_code=402,
                            detail={
                                "code": "AMOUNT_MISMATCH",
                                "message": "Payment amount does not cover the fare.",
                            },
                        )

                await db_supabase.update_ride(
                    ride_id,
                    {
                        "payment_status": intent.status,
                        "payment_intent_id": payment_intent_id,
                    },
                )

            return {"status": intent.status, "mock": False}
        except HTTPException:
            # Ownership 403s above must reach the client, not become a 500.
            raise
        except Exception as e:
            logger.error(f"Stripe error: {e}", exc_info=True)
            raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e

    return {"status": "unknown", "mock": True}


