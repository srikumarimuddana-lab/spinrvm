class AddCardRequest(BaseModel):
    """Add-card request body.

    Accepts only a Stripe `payment_method_id` created client-side via
    Stripe.js or @stripe/stripe-react-native. Raw card fields (PAN, CVC,
    expiry) must NEVER flow through the backend — accepting them puts
    the server in PCI-DSS SAQ-D scope. See AUDIT C-PAY-01.
    """

    payment_method_id: str = Field(..., min_length=1, max_length=128)


# Field names that indicate the caller sent raw card data (PAN/CVV/expiry).
# If ANY of these are present in the request body, we refuse to process
# the request at all — before any logging, before JSON parsing by pydantic,
# before touching Stripe. This is the PCI-DSS perimeter.
_RAW_CARD_FIELDS = {
    "card_number",
    "cardNumber",
    "card_no",
    "number",
    "pan",
    "primary_account_number",
    "cvv",
    "cvv2",
    "cvc",
    "cvc2",
    "security_code",
    "card_security_code",
    "expiry",
    "expiration",
    "expiration_date",
    "exp_month",
    "exp_year",
}


@api_router.post("/cards")
@payment_action_limit
async def add_card(request: Request = None, current_user: dict = Depends(get_current_user)):
    """Add a saved card. Requires client-side tokenization.

    Contract:
      - Body must be ``{"payment_method_id": "pm_..."}``.
      - Body must NOT contain any raw-card fields (PAN, CVC, expiry).
      - If stripe_secret_key is unset (demo mode), a fake record is
        returned with a random last4 — the payment_method_id is still
        required for contract parity so the mobile app integrates with
        a single API shape across environments.

    PCI-DSS note: we deliberately raise a plain 400 BEFORE reading the
    full JSON for logging/metrics so an attacker probing the endpoint
    with a PAN does not get it persisted in access logs. The error
    response intentionally does NOT echo the offending keys back.
    """
    # Parse once; reject immediately if the body shape hints at raw card data.
    try:
        data = await request.json()
    except Exception as exc:
        raise HTTPException(status_code=400, detail="Invalid JSON body") from exc

    if not isinstance(data, dict):
        raise HTTPException(status_code=400, detail="Body must be a JSON object")

    forbidden = _RAW_CARD_FIELDS.intersection(data.keys())
    if forbidden:
        # Log that a raw-card POST was attempted but DO NOT log the keys'
        # values. The client needs tokenization; tell them where to look.
        logger.error(
            f"Rejected raw-card POST to /payments/cards from user={current_user.get('id')}: {sorted(forbidden)} present"
        )
        raise HTTPException(
            status_code=400,
            detail=(
                "Raw card data is not accepted. Tokenize card details "
                "client-side using Stripe.js / @stripe/stripe-react-native "
                "and submit only {'payment_method_id': 'pm_...'}."
            ),
        )

    # Validate the allowed shape. Pydantic rejects missing / wrong types with 422.
    try:
        body = AddCardRequest(**data)
    except Exception as exc:
        # B-P3-leak-cleanup: don't interpolate the Pydantic exception
        # repr (which can include field paths and request structure
        # hints). 400 is a 4xx so the framework sanitiser does not
        # rescue this — manual cleanup matters. Body-shape errors
        # should reach clients via FastAPI's RequestValidationError
        # path normally; this except block is the fallback for the
        # ad-hoc dict-driven payload here.
        logger.error("AddCardRequest validation failed", exc_info=exc)
        raise HTTPException(
            status_code=400,
            detail="Invalid request payload.",
        ) from exc

    payment_method_id = body.payment_method_id

    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")

    if not stripe_secret:
        # Demo mode — fabricate a response. Requires payment_method_id for
        # shape parity with production so mobile has one integration path.
        logger.info(f"[DEMO] Card added via {payment_method_id[:8]}...")
        return {
            "id": payment_method_id,
            "brand": "Visa",
            "last4": "4242",
            "exp_month": 12,
            "exp_year": 2030,
            "is_default": True,
        }

    try:
        # Attach the client-tokenized PaymentMethod to the customer.
        # The PAN never touched our server — the token came from Stripe.js.
        #
        # Wrapped in the repair helper because this is the endpoint a rider
        # reaches when trying to recover from the cutover: attaching to a
        # customer the live key cannot see fails `resource_missing`, which
        # without repair leaves them permanently unable to add ANY card.
        async def _attach(cid: str):
            return await asyncio.to_thread(
                lambda: stripe.PaymentMethod.attach(payment_method_id, customer=cid, api_key=stripe_secret)
            )

        customer_id, pm = await with_customer_repair(current_user["id"], stripe_secret, _attach)

        # Confirm with SetupIntent — saves card for future off-session use.

        si = await asyncio.to_thread(
            lambda: stripe.SetupIntent.create(
                customer=customer_id,
                payment_method=pm.id,
                confirm=True,
                automatic_payment_methods={"enabled": True, "allow_redirects": "never"},
                api_key=stripe_secret,
                idempotency_key=f"setup-card-{current_user['id']}-{pm.id}",
            )
        )

        # Set as default if first card
        user = await db_supabase.get_user_by_id(current_user["id"])
        if not user.get("default_payment_method"):
            await db_supabase.update_one("users", {"id": current_user["id"]}, {"default_payment_method": pm.id})
            await asyncio.to_thread(
                lambda: stripe.Customer.modify(
                    customer_id,
                    invoice_settings={"default_payment_method": pm.id},
                    api_key=stripe_secret,
                )
            )

        logger.info(f"Card added: {pm.card.brand} ****{pm.card.last4} | SetupIntent: {si.id} ({si.status})")

        return {
            "id": pm.id,
            "brand": pm.card.brand.capitalize(),
            "last4": pm.card.last4,
            "exp_month": pm.card.exp_month,
            "exp_year": pm.card.exp_year,
            "is_default": not bool(user.get("default_payment_method")),
            "setup_intent_id": si.id,
            "setup_intent_status": si.status,
        }
    except stripe.error.CardError as e:
        raise PaymentMethodInvalidException(
            message=e.user_message or "Card declined",
            message_key=ErrorKeys.PAYMENT_METHOD_INVALID,
            action_hint="Add a different card",
        ) from e
    except stripe.error.StripeError as e:
        logger.error(f"Stripe API error on add-card: {e}", exc_info=True)
        raise HTTPException(status_code=502, detail="Payment service unavailable. Please try again.") from e
    except HTTPException:
        # Preserve deliberate status codes raised inside the try (the
        # re-provision kill switch's 503).
        raise
    except Exception as e:
        logger.error(f"Unexpected error on add-card: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e


@api_router.post("/cards/{card_id}/default")
@payment_action_limit
async def set_default_card(
    card_id: str,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Set card as default. Updates both our DB and Stripe customer.

    C7: Stripe is updated FIRST; the DB default is only written once Stripe
    accepts it, so a Stripe failure can't leave our DB pointing at a default the
    payment processor doesn't know about. On Stripe error we surface 502 (not a
    silent success) so the client retries.
    """
    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")
    user = await db_supabase.get_user_by_id(current_user["id"])
    if stripe_secret:
        try:
            cid = user.get("stripe_customer_id") if user else None
            if cid:
                # WS-18: verify the card belongs to this customer before
                # promoting it to default. Stripe scopes the modify to the
                # customer, but an explicit ownership check prevents a
                # confusing error surface and guards the non-Stripe fallback.
                methods = await asyncio.to_thread(
                    lambda: stripe.PaymentMethod.list(customer=cid, type="card", api_key=stripe_secret)
                )
                if card_id not in [m.id for m in methods.data]:
                    raise HTTPException(status_code=404, detail="Card not found")
                await asyncio.to_thread(
                    lambda: stripe.Customer.modify(
                        cid,
                        invoice_settings={"default_payment_method": card_id},
                        api_key=stripe_secret,
                    )
                )
        except HTTPException:
            raise
        except Exception as e:
            logger.error(f"Stripe set default failed for card {card_id}: {e}", exc_info=True)
            raise HTTPException(status_code=502, detail="Could not update your default card. Please try again.") from e
    else:
        # WS-18: without Stripe, verify card_id matches the user's existing
        # payment method. Accepting arbitrary strings here would let any
        # caller write garbage into their own default_payment_method field.
        if not user or user.get("default_payment_method") != card_id:
            saved = user.get("saved_payment_methods") if user else None
            if not saved or card_id not in (saved if isinstance(saved, list) else []):
                raise HTTPException(status_code=404, detail="Card not found")

    await db_supabase.update_one("users", {"id": current_user["id"]}, {"default_payment_method": card_id})

    asyncio.create_task(
        _audit_log_user(
            current_user,
            "default_payment_method_set",
            "users",
            current_user["id"],
            {"card_id": card_id},
        )
    )
    return {"success": True}


@api_router.delete("/cards/{card_id}")
@payment_action_limit
async def delete_card(
    card_id: str,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Detach card from Stripe and re-point the default if needed.

    C7: the Stripe detach must SUCCEED before we mutate our DB. Previously a
    failed detach was logged-and-ignored, then the DB default was cleared anyway
    — leaving the card live in Stripe but gone from the UI. Now a failed detach
    raises 502 and the DB is left untouched.

    Last-card guard: the user must always keep at least one card on file, so
    removing their only card is refused with 409 — they add another card first.

    Default reassignment: when the removed card was the default (and, per the
    guard above, at least one other card remains) the most recently added
    remaining card is auto-promoted to default in both Stripe and our DB, so the
    user is never left with saved cards but no default to charge.
    """
    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")

    # Read the user once up front so we know whether this is the default card
    # BEFORE mutating anything in Stripe.
    user = await db_supabase.get_user_by_id(current_user["id"])
    is_default = bool(user and user.get("default_payment_method") == card_id)
    customer_id = user.get("stripe_customer_id") if user else None

    # Enumerate saved cards up front — used both to block removing the last card
    # and to pick the replacement default. Stripe returns most-recent-first.
    saved_ids: list[str] = []
    if stripe_secret and customer_id:
        try:
            methods = await asyncio.to_thread(
                lambda: stripe.PaymentMethod.list(customer=customer_id, type="card", api_key=stripe_secret)
            )
            saved_ids = [m.id for m in methods.data]
        except Exception as e:
            logger.error(f"delete_card: could not list cards ({card_id}): {e}", exc_info=True)
            raise HTTPException(status_code=502, detail="Could not remove your card. Please try again.") from e

        # Keep at least one card on file.
        if len(saved_ids) <= 1:
            raise HTTPException(
                status_code=409,
                detail="You need at least one card on file. Add another card before removing this one.",
            )

    # WS-18: verify the card belongs to this user before detaching.
    # Without this, an attacker who knows another user's pm_... ID can
    # detach it using the platform secret key.
    if stripe_secret:
        if card_id not in saved_ids:
            raise HTTPException(status_code=404, detail="Card not found")
        try:
            await asyncio.to_thread(lambda: stripe.PaymentMethod.detach(card_id, api_key=stripe_secret))
        except Exception as e:
            logger.error(f"Stripe detach failed for card {card_id}: {e}", exc_info=True)
            raise HTTPException(status_code=502, detail="Could not remove your card. Please try again.") from e

    if not is_default:
        return {"success": True}

    # The default card was removed — promote the most recently added remaining
    # card (guard above guarantees at least one exists when Stripe is configured).
    new_default: str | None = next((cid for cid in saved_ids if cid != card_id), None)
    if new_default and stripe_secret and customer_id:
        try:
            await asyncio.to_thread(
                lambda: stripe.Customer.modify(
                    customer_id,
                    invoice_settings={"default_payment_method": new_default},
                    api_key=stripe_secret,
                )
            )
        except Exception as e:
            logger.error(f"delete_card: could not set new default {new_default} in Stripe: {e}", exc_info=True)
            raise HTTPException(status_code=502, detail="Could not remove your card. Please try again.") from e

    # Point our DB at the promoted card (or clear it when Stripe is unconfigured).
    await db_supabase.update_one("users", {"id": current_user["id"]}, {"default_payment_method": new_default})

    return {"success": True}


@api_router.post("/payment-sheet")
@payment_action_limit
async def create_payment_sheet(
    body: PaymentSheetRequest,
    request: Request = None,
    current_user: dict = Depends(get_current_user),
):
    """Return the three secrets needed to initialise Stripe PaymentSheet.

    The mobile client calls initPaymentSheet({ paymentIntent, ephemeralKey,
    customer }) then presentPaymentSheet() to complete the payment in a
    pre-built Stripe modal that supports Google Pay and Apple Pay without
    any card-form UI on our side.

    Returns:
        paymentIntent:  PaymentIntent client_secret
        ephemeralKey:   EphemeralKey secret (scoped to this customer)
        customer:       Stripe customer ID
        publishableKey: App should already have this; included for convenience
    """
    import time as _time

    settings = await get_app_settings()
    stripe_secret = settings.get("stripe_secret_key", "")
    stripe_pk = settings.get("stripe_publishable_key", "")

    if not stripe_secret:
        raise HTTPException(
            status_code=503,
            detail="Payment processing is not configured. Please contact support.",
        )

    # CS-002: For ride payments use the server-authoritative charge
    # (grand_total + tip) rather than trusting body.amount. body.amount is
    # advisory only — a client can send a lower value to underpay area fees,
    # GST/PST, or tip. _authoritative_ride_charge enforces ownership (403 on
    # rider mismatch) and falls back to total_fare for legacy rides predating
    # grand_total. Non-ride PaymentSheet flows keep using body.amount.
    if body.ride_id:
        charge_amount = await _authoritative_ride_charge(body.ride_id, current_user["id"], body.tip_amount)
    else:
        charge_amount = Decimal(str(body.amount))

    try:
        amount_cents = dollars_to_cents(charge_amount)

        # EphemeralKey lets the PaymentSheet modal manage the customer's
        # saved cards. stripe_version must match the version configured on the
        # Stripe webhook endpoint in the dashboard. Use the single pinned
        # STRIPE_API_VERSION from utils/stripe_config — NOT stripe.api_version,
        # which only equals the pin after configure_stripe() has run and
        # otherwise silently falls back to the SDK's bundled version.
        # ACTION REQUIRED when bumping STRIPE_API_VERSION: update the Stripe
        # dashboard webhook endpoint API version to match.
        #
        # EphemeralKey is the first customer-addressed call in this handler, so
        # it is where a customer stranded by a test→live key rotation surfaces.
        # Repairing here means the PaymentSheet opens (with no saved cards)
        # instead of the rider hitting a dead end at payment time.
        async def _ephemeral(cid: str):
            return await asyncio.to_thread(
                lambda: stripe.EphemeralKey.create(
                    customer=cid,
                    stripe_version=STRIPE_API_VERSION,
                    api_key=stripe_secret,
                )
            )

        customer_id, ephemeral_key = await with_customer_repair(current_user["id"], stripe_secret, _ephemeral)

        if body.client_idempotency_key:
            idempotency_key = body.client_idempotency_key
        elif body.ride_id:
            # Include the charge amount (cents) so a changed-tip retry gets a
            # distinct key (fresh PI) rather than an IdempotencyError. Same
            # amount → same key → still idempotent.
            idempotency_key = f"ps-{body.ride_id}-{current_user['id']}-{amount_cents}"
        else:
            idempotency_key = f"ps-{current_user['id']}-{int(_time.time() // 60)}"

        intent = await asyncio.to_thread(
            lambda: stripe.PaymentIntent.create(
                amount=amount_cents,
                currency="cad",
                customer=customer_id,
                automatic_payment_methods={"enabled": True},
                metadata={"user_id": current_user["id"], "ride_id": body.ride_id or ""},
                api_key=stripe_secret,
                idempotency_key=idempotency_key,
            )
        )

        return {
            "paymentIntent": intent.client_secret,
            "ephemeralKey": ephemeral_key.secret,
            "customer": customer_id,
            "publishableKey": stripe_pk,
        }
    except stripe.error.StripeError as e:
        logger.error("Stripe payment-sheet error", exc_info=True)
        raise HTTPException(status_code=502, detail="Payment provider error. Please try again.") from e
    except HTTPException:
        # Intentional 4xx (ownership 403 from _authoritative_ride_charge)
        # must reach the client, not become a 500.
        raise
    except Exception as e:
        logger.error("payment-sheet unexpected error", exc_info=True)
        raise HTTPException(status_code=500, detail="An internal error occurred. Please try again.") from e
