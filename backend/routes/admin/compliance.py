# ── Knight Archer Insurance — Driver Onboarding Report ───────────────


async def _knight_archer_driver_rows(status: Optional[str]) -> tuple[list[dict], bool]:
    """Pull every onboarded driver's license/status info for Knight Archer
    (a Saskatchewan insurance company Spinr reports driver onboarding to,
    separate from the SGI D00032/D00033 regulator forms). Deliberately
    covers every driver status, not just active — Knight Archer's ask was
    for "driver onboarded, driver license, with all status", i.e. the full
    roster regardless of where a driver currently sits in the pipeline
    (pending/needs_review/active/suspended/banned)."""
    filters: dict = {}
    if status:
        filters["status"] = status

    drivers = await db_supabase.get_rows(
        "drivers",
        filters,
        columns="id,name,first_name,last_name,license_number,license_class,status,created_at",
        order="created_at",
        desc=True,
        limit=_ROW_LIMIT,
    )
    truncated = _check_truncated(len(drivers), "knight_archer_driver_onboarding")
    if not drivers:
        return [], truncated

    # license_number is vault-encrypted at rest — same decrypt helper
    # sgi_forms.py uses for the SGI forms, since this report needs the real
    # license number too, not the encrypted token.
    drivers = [await _decrypt_driver_pii(d) for d in drivers]

    rows = [
        {
            "driver_name": d.get("name") or f"{d.get('first_name', '')} {d.get('last_name', '')}".strip() or d["id"],
            "license_number": d.get("license_number") or "",
            "license_class": d.get("license_class") or "",
            "status": d.get("status") or "",
            "onboarded_at": report_branding.format_report_timestamp(d.get("created_at")),
        }
        for d in drivers
    ]
    return rows, truncated


