@pytest.mark.anyio
async def test_period_transition_complete_ride():
    """Completing a ride must call open_period(driver_id, period=1) — driver back to available."""
    from backend.routes import drivers as drv_mod

    mock_open_period = AsyncMock()

    ride_row = {
        "id": RIDE_ID,
        "driver_id": DRIVER_ID,
        "rider_id": "rider-001",
        "status": "in_progress",
        "total_fare": "14.50",
        "pickup_address": "123 Main St",
        "dropoff_address": "456 Elm Ave",
        "created_at": "2026-05-06T10:00:00+00:00",
        "updated_at": "2026-05-06T10:30:00+00:00",
    }
    completed_ride = {**ride_row, "status": "completed"}

    with (
        patch(
            "backend.routes.drivers.db_supabase.get_rows",
            AsyncMock(
                side_effect=[
                    [DRIVER_ROW],  # driver lookup by user_id
                    [ride_row],  # ride lookup for this driver
                    [],  # GPS breadcrumbs (driver_location_history)
                ]
            ),
        ),
        patch("backend.routes.drivers.db_supabase.update_ride", AsyncMock(return_value=completed_ride)),
        patch("backend.routes.drivers.db_supabase.get_ride", AsyncMock(return_value=completed_ride)),
        patch(
            "backend.routes.drivers.manager",
            MagicMock(
                send_personal_message=AsyncMock(),
                broadcast_ride_status=AsyncMock(),
                broadcast_to_admins=AsyncMock(),
            ),
        ),
        patch("backend.routes.drivers.send_push_notification", AsyncMock()),
        patch("utils.insurance_periods.open_period", mock_open_period),
    ):
        await drv_mod.complete_ride(
            ride_id=RIDE_ID,
            current_user={"id": DRIVER_USER_ID},
        )

    # Driver returns to period 1 (available) after completing the ride.
    mock_open_period.assert_awaited_once_with(DRIVER_ID, period=1)
