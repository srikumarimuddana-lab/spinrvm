def _q2(v: Any) -> Decimal:
    """Quantize a money value to 2dp (HALF_UP). Decimal-only — never float."""
    return Decimal(str(v or 0)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


async def _authoritative_ride_charge(ride_id: str, rider_id: str, tip_amount: Decimal) -> Decimal:
    """Server-authoritative amount the rider owes for a ride: grand_total + tip.

    ``grand_total`` already includes area/booking fees and GST/PST; ``total_fare``
    is only the fare-side subtotal. We compute the charge here rather than
    trusting the client-supplied amount so the Stripe (create-intent /
    payment-sheet) paths can never undercharge by omitting fees or tax — the
    same total ``/rides/{id}/process-payment`` settles. Falls back to
    ``total_fare`` only for legacy rides written before ``grand_total`` existed.
    """
    ride = await db_supabase.get_ride(ride_id)
    if not ride:
        raise HTTPException(status_code=404, detail="Ride not found")
    if ride.get("rider_id") != rider_id:
        raise HTTPException(status_code=403, detail="Not authorized to pay for this ride")
    # Explicit None check, not truthiness: a legitimate $0 grand_total (comp /
    # fully-covered ride) must NOT fall through to a non-zero total_fare and
    # overcharge. Only fall back when grand_total was never written (legacy).
    grand_raw = ride.get("grand_total")
    if grand_raw is None:
        grand_raw = ride.get("total_fare", 0)
    grand = _q2(grand_raw)
    return _q2(grand + _q2(tip_amount))


class PaymentIntentRequest(BaseModel):
    """Request body for POST /payments/create-intent."""

    amount: Decimal = Field(..., gt=0, le=100000, decimal_places=2, description="Amount in CAD (1–100000)")
    ride_id: Optional[str] = None
    # Tip is added on top of the ride's grand_total when ride_id is present.
    # For ride payments the server computes the charge as grand_total + tip and
    # ignores `amount` (advisory only) — see _authoritative_ride_charge.
    tip_amount: Decimal = Field(0, ge=0, le=500, decimal_places=2)
    # UUID v4 generated by the mobile client for each new payment attempt.
    # Prevents Stripe idempotency-key collisions when the same user pays
    # the same fare amount on two separate rides within the same 24 h window.
    client_idempotency_key: Optional[str] = None
    payment_method_id: Optional[str] = None


